import { existsSync, readFileSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";

// `invariance init --apply`: the opt-in half of init that edits the host app so
// it renders themed. Plain `init` stays analysis-only. Every edit is idempotent
// (marker-keyed), so re-running --apply never duplicates anything.

export const GEN_START = "/* INVARIANCE-GENERATED:start — regenerated by `invariance init --apply`, do not hand-edit */";
export const GEN_END = "/* INVARIANCE-GENERATED:end */";
export const SSR_MARKER = "inv-ssr-theme";

const LAYOUT_CANDIDATES = ["app", join("src", "app")].flatMap((dir) =>
  ["layout.tsx", "layout.jsx", "layout.ts", "layout.js"].map((f) => join(dir, f)),
);

export interface NextAppFiles {
  layoutFile: string | null;
  globalsCssFile: string | null;
}

/** Locate the App Router root layout and the global stylesheet it imports. */
export function locateNextApp(root: string): NextAppFiles {
  const layoutRel = LAYOUT_CANDIDATES.find((p) => existsSync(join(root, p)));
  if (!layoutRel) return { layoutFile: null, globalsCssFile: null };
  const layoutFile = join(root, layoutRel);

  const src = readFileSync(layoutFile, "utf8");
  for (const m of src.matchAll(/^\s*import\s+["']([^"']+\.css)["']/gm)) {
    const spec = m[1]!;
    if (!spec.startsWith(".")) continue;
    const file = resolve(dirname(layoutFile), spec);
    if (existsSync(file)) return { layoutFile, globalsCssFile: file };
  }
  const beside = join(dirname(layoutFile), "globals.css");
  return { layoutFile, globalsCssFile: existsSync(beside) ? beside : null };
}

/** The compiled role tokens as a marker-delimited `:root` block. */
export function renderRootBlock(roles: Record<string, string>): string {
  const decls = Object.entries(roles)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join("\n");
  return `${GEN_START}\n:root {\n${decls}\n}\n${GEN_END}\n`;
}

export type EditStatus = "created" | "updated" | "unchanged";

/**
 * Write the role-token baseline into the app's global stylesheet. A prior
 * generated block is replaced in place; otherwise it is appended. The app's own
 * CSS (including its own :root) is preserved verbatim.
 */
export async function patchGlobalsCss(file: string, roles: Record<string, string>): Promise<EditStatus> {
  const block = renderRootBlock(roles);
  const existing = await readFile(file, "utf8");
  const start = existing.indexOf(GEN_START);
  let next: string;
  if (start !== -1) {
    const end = existing.indexOf(GEN_END, start);
    const tail = end !== -1 ? existing.slice(end + GEN_END.length).replace(/^\n/, "") : "";
    next = existing.slice(0, start) + block + tail;
  } else {
    const sepNl = existing === "" || existing.endsWith("\n") ? (existing === "" ? "" : "\n") : "\n\n";
    next = existing + sepNl + block;
  }
  if (next === existing) return "unchanged";
  await writeFile(file, next);
  return start !== -1 ? "updated" : "created";
}

/** Path of the generated design config module for a given layout. */
export function configModuleFile(layoutFile: string): string {
  const ext = /\.(tsx|ts)$/.test(layoutFile) ? "ts" : "js";
  // Beside the app/ directory: `<root>/invariance.config.ts` or `<root>/src/invariance.config.ts`.
  return join(dirname(dirname(layoutFile)), `invariance.config.${ext}`);
}

/** Emit a minimal `@invariance/design` config the SSR helpers read (app id = cookie name). */
export async function writeConfigModule(file: string, appId: string): Promise<EditStatus> {
  if (existsSync(file)) return "unchanged";
  const ts = file.endsWith(".ts");
  const body = ts
    ? `import type { InvarianceConfig } from '@invariance/design'\n\n` +
      `// Generated by \`invariance init --apply\`. Developer-owned: add constraints and\n` +
      `// per-page customization levels here.\n` +
      `export const invarianceConfig: InvarianceConfig = { app: ${JSON.stringify(appId)} }\n`
    : `// Generated by \`invariance init --apply\`. Developer-owned: add constraints and\n` +
      `// per-page customization levels here.\n` +
      `/** @type {import('@invariance/design').InvarianceConfig} */\n` +
      `export const invarianceConfig = { app: ${JSON.stringify(appId)} }\n`;
  await writeFile(file, body);
  return "created";
}

function addImportAfterLast(src: string, line: string): string {
  if (src.includes(line)) return src;
  const imports = [...src.matchAll(/^import\s[^;]*?(?:from\s+)?["'][^"']+["'];?[ \t]*$/gm)];
  const last = imports[imports.length - 1];
  if (!last) return `${line}\n${src}`;
  const eol = last.index! + last[0].length;
  return `${src.slice(0, eol)}\n${line}${src.slice(eol)}`;
}

export type SsrResult = { status: EditStatus } | { status: "skipped"; reason: string };

/**
 * Patch the root layout to inline the user's saved theme into <head> on the
 * server (cookie -> renderThemeCss), so first paint is themed with no flash.
 * Text-anchored and conservative: a layout shape we don't recognise is left
 * untouched and reported, never half-edited.
 */
export async function injectSsrInlining(layoutFile: string, configFile: string): Promise<SsrResult> {
  const original = await readFile(layoutFile, "utf8");
  if (original.includes(SSR_MARKER)) return { status: "unchanged" };

  const fnMatch = /export\s+default\s+(async\s+)?function\b/.exec(original);
  if (!fnMatch) return { status: "skipped", reason: "no `export default function` root layout" };
  const returnRe = /(\n[ \t]*)return\s*\(/;
  if (!returnRe.test(original.slice(fnMatch.index))) {
    return { status: "skipped", reason: "root layout has no `return (` to anchor the SSR theme" };
  }
  const hasHead = /<\/head>/.test(original);
  const htmlOpen = /<html\b[^>]*>/.exec(original);
  if (!hasHead && !htmlOpen) return { status: "skipped", reason: "root layout renders no <html>/<head>" };

  const q = /^import[^\n]*'/m.test(original) ? "'" : '"';
  let configSpec = relative(dirname(layoutFile), configFile).split(sep).join("/").replace(/\.(ts|js)$/, "");
  if (!configSpec.startsWith(".")) configSpec = `./${configSpec}`;

  let src = original;
  src = addImportAfterLast(src, `import { headers } from ${q}next/headers${q}`);
  src = addImportAfterLast(src, `import { renderThemeCss, themeFromCookieHeader } from ${q}@invariance/design${q}`);
  src = addImportAfterLast(src, `import { invarianceConfig } from ${q}${configSpec}${q}`);

  const fnIdx = src.search(/export\s+default\s+(async\s+)?function\b/);
  const head = src.slice(0, fnIdx);
  let tail = src.slice(fnIdx).replace(/^export\s+default\s+function\b/, "export default async function");
  tail = tail.replace(
    returnRe,
    (_m, nl: string) =>
      `${nl}// Inline the user's saved theme so first paint is themed (no flash).` +
      `${nl}const cookieHeader = (await headers()).get(${q}cookie${q})` +
      `${nl}const ssrCss = renderThemeCss(themeFromCookieHeader(cookieHeader, invarianceConfig), invarianceConfig)` +
      `\n${nl}return (`,
  );
  src = head + tail;

  const styleTag = `{ssrCss ? <style id="${SSR_MARKER}" dangerouslySetInnerHTML={{ __html: ssrCss }} /> : null}`;
  if (hasHead) {
    src = src.replace(/([ \t]*)<\/head>/, (_m, indent: string) => `${indent}  ${styleTag}\n${indent}</head>`);
  } else {
    src = src.replace(/<html\b[^>]*>/, (open) => `${open}\n        <head>${styleTag}</head>`);
  }

  await writeFile(layoutFile, src);
  return { status: "created" };
}

export interface ApplyReport {
  edits: Array<{ file: string; status: EditStatus }>;
  skipped: Array<{ what: string; reason: string }>;
}

/** Apply the themeable baseline to a Next.js App Router app. */
export async function applyInit(root: string, appId: string, roles: Record<string, string>): Promise<ApplyReport> {
  const report: ApplyReport = { edits: [], skipped: [] };
  const { layoutFile, globalsCssFile } = locateNextApp(root);
  if (!layoutFile) {
    report.skipped.push({ what: "apply", reason: "no Next.js App Router root layout (app/layout.* or src/app/layout.*)" });
    return report;
  }

  if (globalsCssFile) {
    report.edits.push({ file: globalsCssFile, status: await patchGlobalsCss(globalsCssFile, roles) });
  } else {
    report.skipped.push({ what: "globals.css", reason: "root layout imports no local stylesheet" });
  }

  const configFile = configModuleFile(layoutFile);
  const ssr = await injectSsrInlining(layoutFile, configFile);
  if (ssr.status === "skipped") {
    report.skipped.push({ what: "SSR theme inlining", reason: ssr.reason });
  } else {
    report.edits.push({ file: configFile, status: await writeConfigModule(configFile, appId) });
    report.edits.push({ file: layoutFile, status: ssr.status });
  }
  return report;
}
